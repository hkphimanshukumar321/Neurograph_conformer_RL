import argparse
import logging
import pandas as pd
from pathlib import Path

from src.datasets.chisco import parse_chisco
from src.datasets.thinking_out_loud import parse_thinking_out_loud
from src.datasets.karaone import parse_karaone
from src.datasets.zuco import parse_zuco

logging.basicConfig(level=logging.INFO, format="[%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

def find_dataset_roots(detected_csv: str) -> dict:
    """
    Reads detected_datasets.csv and infers the root path for each dataset.
    Returns dict: {dataset_name: list_of_root_paths}
    """
    df = pd.read_csv(detected_csv)
    dataset_roots = {}
    
    for dataset, group in df.groupby("dataset"):
        roots = set()
        for path in group["path"].dropna():
            p = Path(path)
            
            # For BIDS datasets, the root is exactly the folder BEFORE 'sub-*'
            if dataset in ["chisco", "thinking_out_loud"]:
                if p.name == "participants.tsv":
                    roots.add(str(p.parent))
                elif any(part.startswith("sub-") for part in p.parts):
                    sub_idx = [i for i, part in enumerate(p.parts) if part.startswith("sub-")][0]
                    roots.add(str(Path(*p.parts[:sub_idx])))
                # Ignored: random files matching the keyword but not in BIDS structure
            else:
                # For ZuCo and KaraOne, we find the part of the path named 'zuco' or 'karaone'
                target_name = "zuco" if dataset == "zuco" else "karaone"
                found_match = False
                for i, part in enumerate(p.parts):
                    if target_name in part.lower():
                        roots.add(str(Path(*p.parts[:i+1])))
                        found_match = True
                        break
                if not found_match:
                    roots.add(str(p.parent))
                    
        # Filter out _linked symlink folders
        filtered_roots = {r for r in roots if "_linked" not in r}
        
        # Consolidate: keep the shortest valid roots to avoid duplicates
        sorted_roots = sorted(list(filtered_roots), key=lambda x: len(x))
        final_roots = []
        for r in sorted_roots:
            if not any(r.startswith(fr) and r != fr for fr in final_roots):
                final_roots.append(r)
                
        dataset_roots[dataset] = final_roots
        
    return dataset_roots

def main():
    parser = argparse.ArgumentParser(description="Build common ground manifests from raw datasets.")
    parser.add_argument("--detected-csv", type=str, default="data/processed/manifests/detected_datasets.csv",
                        help="Path to detected_datasets.csv generated by scanner script.")
    parser.add_argument("--out-dir", type=str, default="data/processed/manifests",
                        help="Output directory for unified TSV/CSV files.")
    args = parser.parse_args()
    
    detected_csv = Path(args.detected_csv)
    out_dir = Path(args.out_dir)
    
    if not detected_csv.exists():
        logger.error(f"{detected_csv} not found. Ensure scripts/02_scan_server_datasets.sh ran successfully.")
        return
        
    out_dir.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Reading detected datasets from {detected_csv}")
    dataset_roots = find_dataset_roots(detected_csv)
    
    all_subjects = []
    all_sessions = []
    all_trials = []
    
    parsers = {
        "chisco": parse_chisco,
        "thinking_out_loud": parse_thinking_out_loud,
        "karaone": parse_karaone,
        "zuco": parse_zuco
    }
    
    for dataset, roots in dataset_roots.items():
        logger.info(f"Processing dataset '{dataset}' from {len(roots)} root(s)...")
        parse_fn = parsers.get(dataset)
        
        if not parse_fn:
            logger.warning(f"No parser implemented for {dataset}. Skipping.")
            continue
            
        for root in roots:
            logger.info(f"  -> Scanning {root}")
            subjects_df, sessions_df, trials_df = parse_fn(root)
            
            if not subjects_df.empty: all_subjects.append(subjects_df)
            if not sessions_df.empty: all_sessions.append(sessions_df)
            if not trials_df.empty: all_trials.append(trials_df)
            
    # Combine and save
    logger.info(f"Combining and saving to {out_dir}")
    
    if all_subjects:
        final_subjects = pd.concat(all_subjects, ignore_index=True).drop_duplicates(subset=["subject_id", "dataset"])
        final_subjects.to_csv(out_dir / "subjects.tsv", sep='\t', index=False)
        logger.info(f"Saved subjects.tsv ({len(final_subjects)} rows)")
    else:
        logger.warning("No subjects found.")
        
    if all_sessions:
        final_sessions = pd.concat(all_sessions, ignore_index=True).drop_duplicates(subset=["session_id"])
        final_sessions.to_csv(out_dir / "sessions.tsv", sep='\t', index=False)
        logger.info(f"Saved sessions.tsv ({len(final_sessions)} rows)")
        
    if all_trials:
        final_trials = pd.concat(all_trials, ignore_index=True).drop_duplicates(subset=["trial_id"])
        final_trials.to_csv(out_dir / "trials.csv", index=False)
        logger.info(f"Saved trials.csv ({len(final_trials)} rows)")
        
    # Create empty channels.tsv for now
    channels_df = pd.DataFrame(columns=["dataset", "channel_name", "channel_type"])
    channels_df.to_csv(out_dir / "channels.tsv", sep='\t', index=False)
    logger.info("Saved channels.tsv (template)")
    
    logger.info("Manifest building complete.")

if __name__ == "__main__":
    main()
